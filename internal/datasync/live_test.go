// live is two real Postgres servers a test may do anything to. Every other
// test here meets a fake that answers by what a query starts with, so this
// is the only one that knows what a server says back.
//
// It runs when ZOCTL_LIVE_PG_SOURCE and ZOCTL_LIVE_PG_TARGET hold the URL
// of a superuser on each, and the target can reach the source by the
// source's URL. The source needs wal_level = logical. It makes databases
// of its own on both and drops them when it ends.
type live struct {
	t        *testing.T
	src, dst string // the test's database on each server
	mover    string // the source's database as the move's role
	noise    string // another database on the source
	slot     string
	admin    map[string]*liveConn
}

func in(server, database string) string {
	u, _ := url.Parse(server)
	u.Path = "/" + database
	return u.String()
}

func (l *live) conn(u string) *liveConn {
	l.t.Helper()
	if c := l.admin[u]; c != nil {
		return c
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	c, err := liveConnect(ctx, u)
	if err != nil {
		// The error can carry the URL, and the URL a password.
		l.t.Fatal("a live server didn't take the connection")
	}
	l.admin[u] = c
	return c
}

func (l *live) exec(u, sql string, args ...any) {
	l.t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	if _, err := l.conn(u).Exec(ctx, sql, args...); err != nil {
		l.t.Fatalf("%.60s: %v", sql, err)
	}
}

func (l *live) value(u, sql string, args ...any) string {
	l.t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	var v string
	if err := l.conn(u).QueryRow(ctx, sql, args...).Scan(&v); err != nil {
		l.t.Fatalf("%.60s: %v", sql, err)
	}
	return v
}

func newLive(t *testing.T) *live {
	source, target := os.Getenv("ZOCTL_LIVE_PG_SOURCE"), os.Getenv("ZOCTL_LIVE_PG_TARGET")
	if source == "" || target == "" {
		t.Skip("ZOCTL_LIVE_PG_SOURCE and ZOCTL_LIVE_PG_TARGET name no servers to try this on")
	}
	b := make([]byte, 4)
	rand.Read(b)
	name := "zoctl_live_" + hex.EncodeToString(b)
	l := &live{t: t, src: in(source, name), dst: in(target, name), noise: in(source, name+"_noise"), slot: name, admin: map[string]*liveConn{}}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
		defer cancel()
		// A subscription is let go of its slot first, so dropping it
		// asks nothing of the source.
		for _, db := range []string{l.dst, in(target, name+"_other")} {
			c, err := liveConnect(ctx, db)
			if err != nil {
				continue
			}
			for _, sql := range []string{"ALTER SUBSCRIPTION zoctl_orders DISABLE", "ALTER SUBSCRIPTION zoctl_orders SET (slot_name = NONE)", "DROP SUBSCRIPTION zoctl_orders"} {
				c.Exec(ctx, sql)
			}
			c.Close(ctx)
		}
		for _, c := range l.admin {
			c.Close(ctx)
		}
		for server, dbs := range map[string][]string{source: {name, name + "_noise"}, target: {name, name + "_other"}} {
			c, err := liveConnect(ctx, server)
			if err != nil {
				continue
			}
			for _, db := range dbs {
				c.Exec(ctx, "DROP DATABASE IF EXISTS "+db+" WITH (FORCE)")
			}
			c.Exec(ctx, "SELECT pg_drop_replication_slot(slot_name) FROM pg_replication_slots WHERE slot_name = $1 OR slot_name ~ '^pg_[0-9]+_sync_' AND NOT active", name)
			c.Exec(ctx, "DROP ROLE IF EXISTS "+name)
			c.Close(ctx)
		}
	})
	for server, dbs := range map[string][]string{source: {name, name + "_noise"}, target: {name, name + "_other"}} {
		for _, db := range dbs {
			l.exec(server, "CREATE DATABASE "+db)
		}
	}
	// What copy_schema has to make on the target besides the tables: a
	// serial's sequence and default, other defaults, a check, an identity
	// column, a generated one, a foreign key and an index.
	l.exec(l.src, `CREATE TABLE orders (id bigserial PRIMARY KEY, note text NOT NULL DEFAULT 'it''s new',
	  made timestamptz NOT NULL DEFAULT now(), CONSTRAINT short_note CHECK (length(note) < 100))`)
	l.exec(l.src, `CREATE TABLE items (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id bigint NOT NULL REFERENCES orders (id),
	  price numeric(10,2), doubled numeric GENERATED ALWAYS AS (price * 2) STORED)`)
	l.exec(l.src, `CREATE INDEX items_order ON items (order_id)`)
	l.exec(l.src, `CREATE TABLE unpublished (id int PRIMARY KEY)`)
	l.exec(l.src, `INSERT INTO orders (note) SELECT 'order ' || g FROM generate_series(1, 20000) g`)
	l.exec(l.src, `INSERT INTO items (id, order_id, price) SELECT g, g, g / 7.0 FROM generate_series(1, 20000) g`)
	l.exec(l.src, `CREATE PUBLICATION zoctl_live FOR TABLE orders, items`)
	// What the move connects to the source as: a role that can replicate
	// and read the published tables, and nothing more.
	secret := make([]byte, 16)
	rand.Read(secret)
	l.exec(l.src, "CREATE ROLE "+name+" LOGIN REPLICATION PASSWORD '"+hex.EncodeToString(secret)+"'")
	l.exec(l.src, "GRANT SELECT ON orders, items TO "+name)
	mover, _ := url.Parse(l.src)
	mover.User = url.UserPassword(name, hex.EncodeToString(secret))
	l.mover = mover.String()
	l.value(l.src, `SELECT slot_name::text FROM pg_create_logical_replication_slot($1, 'pgoutput')`, name)
	l.exec(l.noise, `CREATE TABLE n (i int)`)
	// Another database on the target has a subscription of the same
	// name. pg_subscription lists every database's.
	l.exec(in(target, name+"_other"), `CREATE SUBSCRIPTION zoctl_orders CONNECTION 'host=192.0.2.1 dbname=x' PUBLICATION p WITH (connect = false)`)
	return l
}

func (l *live) sync() (*Sync, *transfer.Workspace) {
	l.t.Helper()
	m, err := ParseMove([]byte(fmt.Sprintf(`{"version":1,"source":"aws","target":"gcp","datasets":[{"name":"orders","kind":"postgres",
	 "from_env":"SOURCE_DB","to_env":"TARGET_DB","publication":"zoctl_live","slot":%q,"copy_schema":true}],"limits":{"max_objects":1,"max_bytes":1,"hours":1}}`, l.slot)))
	if err != nil {
		l.t.Fatal(err)
	}
	s, err := Open(m, Options{Env: func(k string) string { return map[string]string{"SOURCE_DB": l.mover, "TARGET_DB": l.dst}[k] }})
	if err != nil {
		l.t.Fatal(err)
	}
	l.t.Cleanup(s.Close)
	w, err := transfer.OpenWorkspace(filepath.Join(l.t.TempDir(), "ws"))
	if err != nil {
		l.t.Fatal(err)
	}
	l.t.Cleanup(func() { w.Close() })
	return s, w
}

// run is one approval: plan, approve, and rounds until the data checks out.
func (l *live) run(s *Sync, w *transfer.Workspace, rounds int) Status {
	l.t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	p, err := s.Plan(ctx)
	if err != nil || p.Blocked() {
		l.t.Fatalf("plan: %v %+v", err, p)
	}
	st, err := s.Run(ctx, w, p, p.Digest, RunOptions{Every: time.Second, Rounds: rounds})
	if err != nil {
		l.t.Fatalf("run: %v", err)
	}
	return st
}

// noise is what a real server writes that isn't the move's: another
// database's rows, a table the publication leaves out, a checkpoint and a
// new WAL file.
func (l *live) quietNoise() {
	l.t.Helper()
	l.exec(l.noise, `INSERT INTO n SELECT generate_series(1, 1000)`)
	l.exec(l.noise, `CHECKPOINT`)
	l.value(l.noise, `SELECT pg_switch_wal()::text`)
}

func TestLivePostgres(t *testing.T) {
	l := newLive(t)
	ctx := context.Background()
	s, w := l.sync()

	// The first approval copies both tables and ends caught up, with
	// the subscription stopped.
	st := l.run(s, w, 6)
	if !st.Verified() || st.Stage != "verified" {
		t.Fatalf("first run: %+v", st)
	}
	if got := l.value(l.dst, `SELECT count(*)::text FROM orders`); got != "20000" {
		t.Fatalf("%s orders on the target", got)
	}
	// copy_schema made the rest of the schema, so an insert on the
	// target gets an id and the cutover has sequences to set.
	for query, want := range map[string]string{
		`SELECT pg_get_expr(adbin, adrelid) FROM pg_attrdef WHERE adrelid = 'orders'::regclass AND adnum = 1`:                                "nextval('orders_id_seq'::regclass)",
		`SELECT pg_get_expr(adbin, adrelid) FROM pg_attrdef WHERE adrelid = 'orders'::regclass AND adnum = 2`:                                "'it''s new'::text",
		`SELECT pg_get_expr(adbin, adrelid) FROM pg_attrdef WHERE adrelid = 'orders'::regclass AND adnum = 3`:                                "now()",
		`SELECT pg_get_serial_sequence('orders', 'id')`:                                                                                      "public.orders_id_seq",
		`SELECT attidentity::text FROM pg_attribute WHERE attrelid = 'items'::regclass AND attname = 'id'`:                                   "d",
		`SELECT pg_get_serial_sequence('items', 'id')`:                                                                                       "public.items_id_seq",
		`SELECT doubled::text FROM items WHERE id = 7`:                                                                                       "2.00",
		`SELECT string_agg(contype::text, '' ORDER BY contype) FROM pg_constraint WHERE conrelid IN ('orders'::regclass, 'items'::regclass)`: "cfpp",
		`SELECT coalesce(to_regclass('items_order')::text, '')`:                                                                              "items_order",
	} {
		if got := l.value(l.dst, query); got != want {
			t.Fatalf("%s: %q, want %q", query, got, want)
		}
	}
	if got := l.value(l.dst, `SELECT subenabled::text FROM pg_subscription WHERE subname = 'zoctl_orders' AND subdbid = (SELECT oid FROM pg_database WHERE datname = current_database())`); got != "false" {
		t.Fatalf("the subscription is enabled after the run: %s", got)
	}
	// The slots Postgres made for the first copy are gone again.
	if got := l.value(l.src, `SELECT count(*)::text FROM pg_replication_slots`); got != "1" {
		t.Fatalf("%s slots on the source after the copy", got)
	}

	// WAL that has none of the move's rows in it isn't lag, and isn't a
	// writer: a server always has some.
	set := s.sets[0].(*pgSet)
	before, err := set.Position(ctx)
	if err != nil {
		t.Fatal(err)
	}
	l.quietNoise()
	if st, err = s.Check(ctx); err != nil || !st.Verified() {
		t.Fatalf("after WAL that isn't the move's: %v %+v", err, st)
	}
	l.exec(l.src, `INSERT INTO unpublished SELECT generate_series(1, 100)`)
	time.Sleep(12 * time.Second) // longer than a session takes to report its writes
	if after, _ := set.Position(ctx); after != before {
		t.Fatalf("writes that aren't the move's moved the position: %s to %s", before, after)
	}
	if st, err = s.Check(ctx); err != nil || !st.Verified() {
		t.Fatalf("after a write to a table that isn't published: %v %+v", err, st)
	}

	// A transaction that has written and not committed: nothing has
	// reached the slot or the counters, and the position still won't
	// stay put.
	open, err := liveConnect(ctx, l.src)
	if err != nil {
		t.Fatal("a live server didn't take the connection")
	}
	defer open.Close(ctx)
	if _, err := open.Exec(ctx, `BEGIN; INSERT INTO orders (note) VALUES ('open')`); err != nil {
		t.Fatal(err)
	}
	one, _ := set.Position(ctx)
	two, _ := set.Position(ctx)
	if one == two || one == before {
		t.Fatalf("an open writer left the position at %s", one)
	}
	if _, err := open.Exec(ctx, `ROLLBACK`); err != nil {
		t.Fatal(err)
	}
	before, _ = set.Position(ctx)

	// A row the target doesn't have is lag, and a writer.
	l.exec(l.src, `INSERT INTO orders (note) VALUES ('late')`)
	l.exec(l.src, `UPDATE items SET price = 1 WHERE id = 7`)
	if st, err = s.Check(ctx); err != nil || st.Verified() || st.Datasets[0].LagBytes == 0 {
		t.Fatalf("a row behind: %v %+v", err, st)
	}
	deadline := time.Now().Add(30 * time.Second)
	for {
		after, err := set.Position(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if after != before {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("a write to the source never moved the position")
		}
		time.Sleep(500 * time.Millisecond)
	}

	// A second approval takes the subscription up where it stopped.
	st = l.run(s, w, 4)
	if !st.Verified() {
		t.Fatalf("second run: %+v", st)
	}
	if got := l.value(l.dst, `SELECT price::text FROM items WHERE id = 7`); got != "1.00" {
		t.Fatalf("the update didn't arrive: %s", got)
	}
	if got := l.value(l.dst, `SELECT note FROM orders ORDER BY id DESC LIMIT 1`); got != "late" {
		t.Fatalf("the insert didn't arrive: %s", got)
	}

	// Sequences don't replicate; a cutover sets the ones the target has,
	// which copy_schema made. The role can't read them yet, and the server
	// shows them as if they had never been used.
	if p, err := set.Plan(ctx); err != nil || !contains(p.Findings, findingNoSequence) {
		t.Fatalf("plan with a sequence the role can't read: %v %+v", err, p)
	}
	if _, err := set.Sequences(ctx); !errors.Is(err, ErrSequence) {
		t.Fatalf("sequences the role can't read: %v", err)
	}
	l.exec(l.src, "GRANT SELECT ON SEQUENCE orders_id_seq, items_id_seq TO "+l.slot)
	if p, err := set.Plan(ctx); err != nil || contains(p.Findings, findingNoSequence) {
		t.Fatalf("plan: %v %+v", err, p)
	}
	// items_id_seq was never used (every id was given), so only one has a
	// value to set.
	if n, err := set.Sequences(ctx); err != nil || n != 1 {
		t.Fatalf("sequences: %d %v", n, err)
	}
	if got, want := l.value(l.dst, `SELECT last_value::text FROM orders_id_seq`), l.value(l.src, `SELECT last_value::text FROM orders_id_seq`); got != want {
		t.Fatalf("sequence at %s, the source's at %s", got, want)
	}
	// The source's connection can't write, whatever it is asked.
	if _, err := set.src.Rows(ctx, `INSERT INTO unpublished VALUES (1) RETURNING id::text`); err == nil {
		t.Fatal("the source took a write")
	}
}

// liveConn is a test's own session on a live server, which may write and
// take arguments in Exec.
type liveConn struct{ c *pgwire.Conn }

func liveConnect(ctx context.Context, u string) (*liveConn, error) {
	cfg, err := pgwire.ParseURL(u)
	if err != nil {
		return nil, err
	}
	c, err := pgwire.Connect(ctx, cfg)
	if err != nil {
		return nil, err
	}
	return &liveConn{c}, nil
}

func (l *liveConn) Exec(ctx context.Context, sql string, args ...any) (struct{}, error) {
	if len(args) == 0 {
		return struct{}{}, l.c.Exec(ctx, sql)
	}
	_, err := l.c.Rows(ctx, sql, args...)
	return struct{}{}, err
}

type liveRow struct {
	rows [][]string
	err  error
}

func (r liveRow) Scan(v *string) error {
	if r.err != nil {
		return r.err
	}
	if len(r.rows) == 0 || len(r.rows[0]) == 0 {
		return errors.New("no rows")
	}
	*v = r.rows[0][0]
	return nil
}

func (l *liveConn) QueryRow(ctx context.Context, sql string, args ...any) liveRow {
	rows, err := l.c.Rows(ctx, sql, args...)
	return liveRow{rows, err}
}

func (l *liveConn) Close(context.Context) { _ = l.c.Close() }
